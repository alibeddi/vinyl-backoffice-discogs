/**
 * Creates the minimal data the documented walkthrough needs: one tenant, one
 * catalogue product with NO Discogs release attached, and one sellable unit.
 *
 * Leaving the release unattached is deliberate: it lets the completeness check
 * fail first, then pass once the release is attached.
 *
 * Plain CommonJS rather than TypeScript because it runs before any build:
 * compileStrapi() is what turns the project's TypeScript into dist/.
 */
const { compileStrapi, createStrapi } = require('@strapi/strapi');

const TENANT_SLUG = 'test-tenant';

async function findOrCreateTenant(app) {
  const existing = await app.documents('api::tenant.tenant').findFirst({
    filters: { slug: TENANT_SLUG },
  });
  if (existing) return existing;

  return app.documents('api::tenant.tenant').create({
    data: { name: 'Test Tenant', slug: TENANT_SLUG, isActive: true },
  });
}

async function findOrCreateProduct(app, tenantId) {
  const existing = await app.documents('api::product.product').findFirst({
    filters: { tenant: { documentId: tenantId } },
  });
  if (existing) return existing;

  return app.documents('api::product.product').create({
    data: {
      tenant: tenantId,
      productType: 'vinyl',
      title: 'Discovery',
      artist: 'Daft Punk',
      description: 'Second studio album, French touch classic.',
      catalogReference: 'DEMO-DISCOVERY-001',
    },
  });
}

async function findOrCreateUnit(app, tenantId, productId) {
  const existing = await app.documents('api::sellable-unit.sellable-unit').findFirst({
    filters: { tenant: { documentId: tenantId } },
  });
  if (existing) return existing;

  return app.documents('api::sellable-unit.sellable-unit').create({
    data: {
      tenant: tenantId,
      product: productId,
      price: 29.9,
      currency: 'EUR',
      mediaCondition: 'NEAR_MINT',
      sleeveCondition: 'VERY_GOOD_PLUS',
      sellerComment: 'Original French pressing, sleeve slightly worn.',
      saleStatus: 'available',
      quantity: 1,
      internalLocation: 'A1-03',
    },
  });
}

(async () => {
  const app = await createStrapi(await compileStrapi()).load();

  try {
    const tenant = await findOrCreateTenant(app);
    const product = await findOrCreateProduct(app, tenant.documentId);
    const unit = await findOrCreateUnit(app, tenant.documentId, product.documentId);

    process.stdout.write(
      [
        '',
        'Seed complete.',
        `  TENANT_ID=${tenant.documentId}`,
        `  PRODUCT_ID=${product.documentId}`,
        `  UNIT_ID=${unit.documentId}`,
        `  SKU=${unit.sku}   (generated by the backend)`,
        '',
      ].join('\n')
    );
  } finally {
    await app.destroy();
  }

  process.exit(0);
})().catch((error) => {
  process.stderr.write(`Seed failed: ${error.message}\n`);
  process.exit(1);
});
