#!/usr/bin/env bash
#
# Runs the full Discogs workflow against a running server and checks each step.
# Requires: the dev server on $API_URL, and a reachable database.
#
#   npm run develop        # in another terminal
#   npm run e2e
#
set -euo pipefail

API="${API_URL:-http://127.0.0.1:1337/api}"
PASSED=0

step() { printf '\n\033[1m%s\033[0m\n' "$1"; }

# Asserts on the response body so a green run actually means something.
expect() {
  local label="$1" haystack="$2" needle="$3"
  if printf '%s' "$haystack" | grep -q -- "$needle"; then
    printf '  ok   %s\n' "$label"
    PASSED=$((PASSED + 1))
  else
    printf '  FAIL %s\n       expected to find: %s\n       got: %s\n' "$label" "$needle" "$haystack"
    exit 1
  fi
}

expect_status() {
  local label="$1" actual="$2" wanted="$3"
  if [ "$actual" = "$wanted" ]; then
    printf '  ok   %s (HTTP %s)\n' "$label" "$actual"
    PASSED=$((PASSED + 1))
  else
    printf '  FAIL %s: expected HTTP %s, got %s\n' "$label" "$wanted" "$actual"
    exit 1
  fi
}

post() { curl -s -X POST "$1" -H 'Content-Type: application/json' -d "$2"; }
post_status() { curl -s -o /dev/null -w '%{http_code}' -X POST "$1" -H 'Content-Type: application/json' -d "$2"; }

step "0. Reseeding demo data"
SEED_OUTPUT=$(node scripts/seed.js --reset)
TENANT_ID=$(printf '%s' "$SEED_OUTPUT" | sed -n 's/.*TENANT_ID=\([a-z0-9]*\).*/\1/p')
PRODUCT_ID=$(printf '%s' "$SEED_OUTPUT" | sed -n 's/.*PRODUCT_ID=\([a-z0-9]*\).*/\1/p')
UNIT_ID=$(printf '%s' "$SEED_OUTPUT" | sed -n 's/.*UNIT_ID=\([a-z0-9]*\).*/\1/p')
SKU=$(printf '%s' "$SEED_OUTPUT" | sed -n 's/.*SKU=\([A-Z0-9-]*\).*/\1/p')

[ -n "$TENANT_ID" ] || { echo "Seed did not return a tenant id"; exit 1; }
printf '  tenant=%s product=%s unit=%s sku=%s\n' "$TENANT_ID" "$PRODUCT_ID" "$UNIT_ID" "$SKU"
expect "SKU was generated by the backend" "$SKU" '^VIN-[0-9]\{6,\}$'

step "1. Search a Discogs release"
BODY=$(curl -s "$API/discogs/search?tenantId=$TENANT_ID&q=Daft%20Punk")
expect "reference release 123456 is returned" "$BODY" '"releaseId":"123456"'
expect "release carries its catalogue data" "$BODY" '"label":"Virgin"'

step "2. Completeness before attaching a release (must fail)"
BODY=$(post "$API/sellable-units/$UNIT_ID/check-discogs-completeness" "{\"tenantId\":\"$TENANT_ID\"}")
expect "unit is not publishable yet" "$BODY" '"valid":false'
expect "reason is the missing release" "$BODY" 'RELEASE_NOT_ATTACHED'

step "3. Publishing is refused while incomplete"
STATUS=$(post_status "$API/sellable-units/$UNIT_ID/publish-discogs" "{\"tenantId\":\"$TENANT_ID\"}")
expect_status "publication refused" "$STATUS" "400"

step "4. Attach the Discogs release to the catalogue product"
BODY=$(post "$API/products/$PRODUCT_ID/attach-discogs-release" "{\"tenantId\":\"$TENANT_ID\",\"releaseId\":\"123456\"}")
expect "release id stored" "$BODY" '"discogsReleaseId":"123456"'
expect "master id stored" "$BODY" '"discogsMasterId":"654321"'
expect "empty catalogue fields filled from Discogs" "$BODY" '"country":"France"'

step "5. Completeness after attaching"
BODY=$(post "$API/sellable-units/$UNIT_ID/check-discogs-completeness" "{\"tenantId\":\"$TENANT_ID\"}")
expect "unit is now publishable" "$BODY" '"valid":true'

step "6. Publish the unit on Discogs"
BODY=$(post "$API/sellable-units/$UNIT_ID/publish-discogs" "{\"tenantId\":\"$TENANT_ID\"}")
expect "listing is published" "$BODY" '"status":"published"'
expect "external listing id stored" "$BODY" '"externalListingId":"discogs-listing-'
expect "external url stored" "$BODY" 'https://www.discogs.com/sell/item/discogs-listing-'

step "7. Simulate a Discogs sale"
BODY=$(post "$API/sellable-units/$UNIT_ID/simulate-discogs-sale" "{\"tenantId\":\"$TENANT_ID\"}")
expect "unit is sold" "$BODY" '"saleStatus":"sold"'
expect "stock reached zero" "$BODY" '"quantity":0'
expect "listing is no longer offered" "$BODY" '"status":"removed"'

step "8. Selling the same unit again is refused"
STATUS=$(post_status "$API/sellable-units/$UNIT_ID/simulate-discogs-sale" "{\"tenantId\":\"$TENANT_ID\"}")
expect_status "second sale refused" "$STATUS" "400"

step "9. Tenant isolation"
STATUS=$(post_status "$API/sellable-units/$UNIT_ID/check-discogs-completeness" '{"tenantId":"unknowntenantid000000001"}')
expect_status "unknown tenant rejected" "$STATUS" "404"

step "10. A marketplace outage is not reported as an application bug"
STATUS=$(curl -s -o /dev/null -w '%{http_code}' "$API/discogs/search?tenantId=$TENANT_ID&q=FORCE_DISCOGS_ERROR")
expect_status "Discogs failure surfaced as a gateway error" "$STATUS" "502"

printf '\n\033[32mAll %s checks passed.\033[0m\n' "$PASSED"
printf 'Inspect the journal in the admin: Content Manager > Marketplace Sync Event\n'
